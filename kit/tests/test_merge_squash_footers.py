"""Squash messages remove session attribution while keeping ordinary prose."""
from kit.tests import test_merge_squash_message as squash
from kit.tests import test_merge_squash_settings as settings
from kit.tests.helpers import FakeGh
import common


def attribution_lines():
    # Assemble personal-link and address patterns outside tracked text.
    session = "https://claude.ai/code/" + "session_example"
    address = "noreply@" + "anthropic.com"
    lines = [
        "claude-session: example",
        " \tclaude-session: " + session,
        session,
        "Continue at " + session + " for details.",
        "Contact " + address + " for details.",
    ]
    for verb in ("with", "by"):
        footer = "Generated %s " % verb
        lines += [
            footer + "[Claude Code]",
            footer + "[Claude Code](https://claude.com/claude-code)",
            "Build details: " + footer + "[Claude Code].",
            footer + "Claude Code",
            "🤖 " + footer + "Claude Code.",
            " \t" + footer + "Claude Code.",
        ]
    return lines


class SquashFootersTest(FakeGh):
    project = settings.SquashSettingsTest.project
    build = squash.SquashMessageTest.build
    merge_body = squash.SquashMessageTest.merge_body

    def check_messages(self, values, reverse=False):
        self.project(values)
        removed = attribution_lines()
        prose = [
            "Fix the Claude Code session parser",
            "Document Claude integration.",
            "This example was generated with Claude Code for the guide.",
            "Generated by Claude Code examples belong in the guide.",
        ]
        # This co-author has no vendor address: the setting controls it alone.
        coauthor = squash.CO + "Claude <developer@example.com>"
        messages = []
        for index, line in enumerate(removed):
            parts = [prose[index % len(prose)], line, line.swapcase()]
            if reverse:
                parts.reverse()
            messages.append("Change %d\n\n%s" % (index, "\n".join(parts)))
        messages.append("Keep the documentation\n\n" + coauthor)
        if reverse:
            messages.reverse()
        _, body = self.merge_body(messages)

        source = common.git(["log", "--format=%B", "main..issue/1"], cwd=self.work)
        for line in removed:
            self.assertIn(line, source, "the builder commit must retain the input")
            self.assertIn(line.swapcase(), source)
        for line in prose:
            self.assertIn(line, body)
        for index in range(len(removed)):
            self.assertIn("Change %d" % index, body)
        if values.get("Agent attribution"):
            self.assertIn(coauthor, body)
        else:
            self.assertNotIn(coauthor, body)
        body_lines = {line.strip().casefold() for line in body.splitlines()}
        for line in removed:
            with self.subTest(line=line):
                self.assertFalse(line.strip().casefold() in body_lines,
                                 "attribution line survived: %r" % line)

    def test_hook_forms_go_with_default_or_false_attribution(self):
        for values, reverse in (({}, False), ({"Agent attribution": False}, True)):
            with self.subTest(settings=values, reverse=reverse):
                self.check_messages(values, reverse)

    def test_hook_forms_go_with_agent_attribution_on(self):
        self.check_messages({"Agent attribution": True}, reverse=True)
